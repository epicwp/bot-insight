#!/usr/bin/env bash
#
# Prepares the WordPress integration-test environment.
#
#   - Downloads WordPress core into $WP_CORE_DIR (default: .wp-tests/wordpress).
#   - Writes a wp-tests-config.php to $WP_TESTS_CONFIG (default: .wp-tests/wp-tests-config.php).
#   - Creates the test database unless the last argument is "true".
#
# The WordPress test library itself comes from the wp-phpunit/wp-phpunit Composer package;
# tests/integration/bootstrap.php points it at the generated config.
#
# Usage: bin/install-wp-tests.sh <db-name> <db-user> <db-pass> [db-host] [wp-version] [skip-database-creation]
#   wp-version: "latest" (default) or an exact release such as 6.2 or 6.2.6.

set -euo pipefail

if [ $# -lt 3 ]; then
	echo "Usage: $0 <db-name> <db-user> <db-pass> [db-host] [wp-version] [skip-database-creation]" >&2
	exit 1
fi

DB_NAME="$1"
DB_USER="$2"
DB_PASS="$3"
DB_HOST="${4-localhost}"
WP_VERSION="${5-latest}"
SKIP_DB_CREATE="${6-false}"

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WP_CORE_DIR="${WP_CORE_DIR:-$root/.wp-tests/wordpress}"
WP_TESTS_CONFIG="${WP_TESTS_CONFIG:-$root/.wp-tests/wp-tests-config.php}"
WP_CORE_DIR="${WP_CORE_DIR%/}"

download() {
	if command -v curl >/dev/null 2>&1; then
		curl -fsSL "$1" -o "$2"
	else
		wget -nv -O "$2" "$1"
	fi
}

install_core() {
	local archive marker tmp
	if [ "$WP_VERSION" = "latest" ]; then
		archive="https://wordpress.org/latest.tar.gz"
	elif [[ "$WP_VERSION" =~ ^[0-9]+\.[0-9]+(\.[0-9]+)?$ ]]; then
		archive="https://wordpress.org/wordpress-$WP_VERSION.tar.gz"
	else
		echo "Unsupported WordPress version: $WP_VERSION" >&2
		exit 1
	fi

	marker="$WP_CORE_DIR/.bot-insight-wp-version"
	if [ "$WP_VERSION" != "latest" ] && [ -f "$marker" ] && [ "$(cat "$marker")" = "$WP_VERSION" ]; then
		echo "WordPress $WP_VERSION already in $WP_CORE_DIR"
		return
	fi

	tmp="$(mktemp -d)"
	download "$archive" "$tmp/wordpress.tar.gz"
	tar -xzf "$tmp/wordpress.tar.gz" -C "$tmp"
	rm -rf "$WP_CORE_DIR"
	mkdir -p "$(dirname "$WP_CORE_DIR")"
	mv "$tmp/wordpress" "$WP_CORE_DIR"
	rm -rf "$tmp"
	echo "$WP_VERSION" >"$marker"
	echo "WordPress $(sed -n "s/^\$wp_version = '\(.*\)';/\1/p" "$WP_CORE_DIR/wp-includes/version.php") installed in $WP_CORE_DIR"
}

write_config() {
	mkdir -p "$(dirname "$WP_TESTS_CONFIG")"
	cat >"$WP_TESTS_CONFIG" <<PHP
<?php
// Generated by bin/install-wp-tests.sh. Do not commit.
define( 'ABSPATH', '$WP_CORE_DIR/' );
define( 'WP_DEFAULT_THEME', 'default' );
define( 'WP_DEBUG', true );
define( 'DB_NAME', '$DB_NAME' );
define( 'DB_USER', '$DB_USER' );
define( 'DB_PASSWORD', '$DB_PASS' );
define( 'DB_HOST', '$DB_HOST' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );
\$table_prefix = 'wptests_';
define( 'WP_TESTS_DOMAIN', 'example.org' );
define( 'WP_TESTS_EMAIL', 'admin@example.org' );
define( 'WP_TESTS_TITLE', 'Test Blog' );
define( 'WP_PHP_BINARY', 'php' );
define( 'WPLANG', '' );
PHP
	echo "Config written to $WP_TESTS_CONFIG"
}

create_db() {
	if [ "$SKIP_DB_CREATE" = "true" ]; then
		return
	fi
	local host="${DB_HOST%%:*}" port="" extra=()
	if [[ "$DB_HOST" == *:* ]]; then
		port="${DB_HOST#*:}"
	fi
	if [ -n "$port" ]; then
		if [[ "$port" =~ ^[0-9]+$ ]]; then
			extra=(--host="$host" --port="$port" --protocol=tcp)
		else
			extra=(--socket="$port")
		fi
	elif [ -n "$host" ]; then
		extra=(--host="$host" --protocol=tcp)
	fi
	MYSQL_PWD="$DB_PASS" mysql --user="$DB_USER" "${extra[@]}" -e "CREATE DATABASE IF NOT EXISTS \`$DB_NAME\`"
	echo "Database $DB_NAME ready"
}

install_core
write_config
create_db
