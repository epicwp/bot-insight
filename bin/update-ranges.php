$base = 'https://';
$sets = array(
	'google'                => array( 'developers.google.com/static/search/apis/ipranges/googlebot.json', 'developers.google.com/static/search/apis/ipranges/special-crawlers.json', 'developers.google.com/static/search/apis/ipranges/user-triggered-fetchers.json' ),
	'bing'                  => array( 'www.bing.com/toolbox/bingbot.json' ),
	'apple'                 => array( 'search.developer.apple.com/applebot.json' ),
	'openai-gptbot'         => array( 'openai.com/gptbot.json' ),
	'openai-searchbot'      => array( 'openai.com/searchbot.json' ),
	'openai-chatgpt-user'   => array( 'openai.com/chatgpt-user.json' ),
	'perplexity-bot'        => array( 'www.perplexity.ai/perplexitybot.json' ),
	'perplexity-user'       => array( 'www.perplexity.ai/perplexity-user.json' ),
	'cloudflare'            => array( 'www.cloudflare.com/ips-v4', 'www.cloudflare.com/ips-v6' ),
);

/**
 * Fetches a URL.
 *
 * @param string $url URL.
 * @return string|null Body, or null on failure.
 */
function bi_fetch( $url ) {
	$ctx  = stream_context_create(
		array(
			'http' => array(
				'timeout'    => 20,
				'user_agent' => 'bot-insight-range-updater',
			),
		)
	);
	$body = @file_get_contents( $url, false, $ctx );
	return ( false === $body || '' === $body ) ? null : $body;
}

/**
 * Extracts CIDR strings from a vendor JSON or plain-text list.
 *
 * @param string $body Response body.
 * @return string[]
 */
function bi_parse( $body ) {
	$out  = array();
	$json = json_decode( $body, true );
	if ( is_array( $json ) ) {
		foreach ( (array) ( $json['prefixes'] ?? array() ) as $row ) {
			foreach ( array( 'ipv4Prefix', 'ipv6Prefix' ) as $key ) {
				if ( isset( $row[ $key ] ) ) {
					$out[] = $row[ $key ];
				}
			}
		}
		return $out;
	}
	foreach ( preg_split( '/\s+/', trim( $body ) ) as $line ) {
		if ( preg_match( '#^[0-9a-f:.]+/\d{1,3}$#i', $line ) ) {
			$out[] = $line;
		}
	}
	return $out;
}

$dir = dirname( __DIR__ ) . '/data/ranges';
if ( ! is_dir( $dir ) ) {
	mkdir( $dir, 0755, true );
}
$meta = array(
	'fetched' => gmdate( 'Y-m-d' ),
	'ok'      => array(),
	'failed'  => array(),
);
foreach ( $sets as $name => $urls ) {
	$ranges = array();
	foreach ( $urls as $url ) {
		$body   = bi_fetch( $base . $url );
		$parsed = null === $body ? array() : bi_parse( $body );
		if ( ! $parsed ) {
			$meta['failed'][] = $url;
			fwrite( STDERR, "FAILED  {$url}\n" );
			continue;
		}
		fwrite( STDERR, 'ok      ' . $url . ' (' . count( $parsed ) . ")\n" );
		$ranges = array_merge( $ranges, $parsed );
	}
	$ranges = array_values( array_unique( $ranges ) );
	if ( ! $ranges ) {
		fwrite( STDERR, "DROPPED {$name}\n" );
		continue;
	}
	$meta['ok'][ $name ] = count( $ranges );
	$code                = "<?php\n// Generated by bin/update-ranges.php. Do not edit.\nreturn " . var_export( $ranges, true ) . ";\n";
	file_put_contents( "{$dir}/{$name}.php", $code );
}
file_put_contents( "{$dir}/_meta.php", "<?php\n// Generated by bin/update-ranges.php. Do not edit.\nreturn " . var_export( $meta, true ) . ";\n" );
